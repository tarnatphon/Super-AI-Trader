def supported() -> list:
    return LANGUAGES


def t(key: str, lang: str = "en") -> str:
    """Translate a key; fall back to English, then the key itself."""
    lang = lang if lang in LANG else "en"
    return LANG.get(lang, {}).get(key, LANG["en"].get(key, key))
